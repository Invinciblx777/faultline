// Generates src/design/tokens.css from the FAULTLINE seed colors with Material Color Utilities.
// Run: node scripts/gen-tokens.mjs  (output is committed; the app never runs this at runtime)
import { writeFileSync } from "node:fs";
import {
  argbFromHex,
  Blend,
  DynamicScheme,
  hexFromArgb,
  MaterialDynamicColors,
  TonalPalette,
} from "@material/material-color-utilities";
// Variant is not exported by the 0.3.0 package; 2 === Variant.TONAL_SPOT.
const TONAL_SPOT = 2;

const SEEDS = { primary: "#5B5F9E", secondary: "#9A6B2A", tertiary: "#C94F9A", neutral: "#7A6F68" };
// Evidence green for "verified fixed", harmonized toward the primary seed so it belongs to the palette.
const SUCCESS_SEED = Blend.harmonize(argbFromHex("#3F8F5A"), argbFromHex(SEEDS.primary));

const palettes = {
  primaryPalette: TonalPalette.fromInt(argbFromHex(SEEDS.primary)),
  secondaryPalette: TonalPalette.fromInt(argbFromHex(SEEDS.secondary)),
  tertiaryPalette: TonalPalette.fromInt(argbFromHex(SEEDS.tertiary)),
  neutralPalette: TonalPalette.fromInt(argbFromHex(SEEDS.neutral)),
  neutralVariantPalette: TonalPalette.fromInt(argbFromHex(SEEDS.neutral)),
};
const success = TonalPalette.fromInt(SUCCESS_SEED);

const ROLES = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "error", "onError", "errorContainer", "onErrorContainer",
  "background", "onBackground",
  "surface", "surfaceDim", "surfaceBright",
  "surfaceContainerLowest", "surfaceContainerLow", "surfaceContainer", "surfaceContainerHigh", "surfaceContainerHighest",
  "onSurface", "onSurfaceVariant", "surfaceVariant",
  "outline", "outlineVariant", "inverseSurface", "inverseOnSurface", "inversePrimary", "scrim", "shadow",
];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);

function scheme(isDark) {
  const s = new DynamicScheme({
    sourceColorArgb: argbFromHex(SEEDS.primary),
    variant: TONAL_SPOT,
    contrastLevel: 0,
    isDark,
    ...palettes,
  });
  const lines = ROLES.map((r) => `  --md-sys-color-${kebab(r)}: ${hexFromArgb(MaterialDynamicColors[r].getArgb(s))};`);
  const t = isDark ? [80, 20, 30, 90] : [40, 100, 90, 10];
  ["success", "on-success", "success-container", "on-success-container"].forEach((name, i) =>
    lines.push(`  --md-sys-color-${name}: ${hexFromArgb(success.tone(t[i]))};`),
  );
  return lines.join("\n");
}

const dark = scheme(true);
const light = scheme(false);

const css = `/*
 * FAULTLINE — Material 3 Expressive tokens. GENERATED by scripts/gen-tokens.mjs; do not hand-edit colors.
 * Seeds: primary ${SEEDS.primary}, secondary ${SEEDS.secondary}, tertiary ${SEEDS.tertiary}, neutral ${SEEDS.neutral}.
 * This is the only file in the web app allowed to contain raw hex values (enforced by pnpm lint:tokens).
 * Dark is the default theme; data-theme="light" or data-theme="system" (+ OS light) selects light.
 */

:root {
  color-scheme: dark;
${dark}
}

:root[data-theme="light"] {
  color-scheme: light;
${light}
}

@media (prefers-color-scheme: light) {
  :root[data-theme="system"] {
    color-scheme: light;
${light.replace(/^ {2}/gm, "    ")}
  }
}

:root {
  /* Semantic roles used across FAULTLINE, mapped onto the M3 scheme. */
  --surface: var(--md-sys-color-surface);
  --surface-dim: var(--md-sys-color-surface-dim);
  --surface-container-lowest: var(--md-sys-color-surface-container-lowest);
  --surface-container-low: var(--md-sys-color-surface-container-low);
  --surface-container: var(--md-sys-color-surface-container);
  --surface-container-high: var(--md-sys-color-surface-container-high);
  --surface-container-highest: var(--md-sys-color-surface-container-highest);
  --on-surface: var(--md-sys-color-on-surface);
  --on-surface-variant: var(--md-sys-color-on-surface-variant);
  --outline: var(--md-sys-color-outline);
  --outline-variant: var(--md-sys-color-outline-variant);
  --scrim: color-mix(in srgb, var(--md-sys-color-scrim) 55%, transparent);

  --primary: var(--md-sys-color-primary);
  --on-primary: var(--md-sys-color-on-primary);
  --primary-container: var(--md-sys-color-primary-container);
  --on-primary-container: var(--md-sys-color-on-primary-container);
  --secondary: var(--md-sys-color-secondary);
  --on-secondary: var(--md-sys-color-on-secondary);
  --secondary-container: var(--md-sys-color-secondary-container);
  --on-secondary-container: var(--md-sys-color-on-secondary-container);
  --tertiary: var(--md-sys-color-tertiary);
  --on-tertiary: var(--md-sys-color-on-tertiary);
  --tertiary-container: var(--md-sys-color-tertiary-container);
  --on-tertiary-container: var(--md-sys-color-on-tertiary-container);

  /* Run identities: baseline = primary (indigo), fault = secondary (amber). */
  --normal: var(--md-sys-color-primary);
  --on-normal: var(--md-sys-color-on-primary);
  --normal-container: var(--md-sys-color-primary-container);
  --on-normal-container: var(--md-sys-color-on-primary-container);
  --fault: var(--md-sys-color-secondary);
  --on-fault: var(--md-sys-color-on-secondary);
  --fault-container: var(--md-sys-color-secondary-container);
  --on-fault-container: var(--md-sys-color-on-secondary-container);

  /* Evidence states. */
  --failure: var(--md-sys-color-error);
  --on-failure: var(--md-sys-color-on-error);
  --failure-container: var(--md-sys-color-error-container);
  --on-failure-container: var(--md-sys-color-on-error-container);
  --success: var(--md-sys-color-success);
  --on-success: var(--md-sys-color-on-success);
  --success-container: var(--md-sys-color-success-container);
  --on-success-container: var(--md-sys-color-on-success-container);
  --incomplete: var(--md-sys-color-tertiary);
  --on-incomplete: var(--md-sys-color-on-tertiary);
  --incomplete-container: var(--md-sys-color-tertiary-container);
  --on-incomplete-container: var(--md-sys-color-on-tertiary-container);
  --unavailable: var(--md-sys-color-outline);
  --unavailable-container: var(--md-sys-color-surface-container-high);

  /* Shape scale (M3 Expressive). Nothing smaller than 8px. */
  --md-sys-shape-corner-small: 8px;
  --md-sys-shape-corner-medium: 16px;
  --md-sys-shape-corner-large: 20px;
  --md-sys-shape-corner-extra-large: 28px;
  --md-sys-shape-corner-full: 9999px;
  --radius-xs: 8px;
  --radius-sm: 8px;
  --radius-md: 16px;
  --radius-lg: 20px;
  --radius-xl: 28px;
  --radius-2xl: 36px;

  /* Type scale: size / line-height / weight. */
  --md-sys-typescale-display-large: 700 57px/64px var(--font-sans);
  --md-sys-typescale-headline-medium: 600 28px/36px var(--font-sans);
  --md-sys-typescale-title-large: 500 22px/28px var(--font-sans);
  --md-sys-typescale-title-medium: 500 16px/24px var(--font-sans);
  --md-sys-typescale-body-medium: 400 14px/20px var(--font-sans);
  --md-sys-typescale-label-medium: 500 12px/16px var(--font-sans);

  /*
   * Motion. Spring tokens (stiffness, damping ratio) for JS springs, plus CSS approximations
   * with matching settle durations. Reduced motion falls back to a 150ms opacity fade.
   */
  --md-sys-motion-spring-default-stiffness: 380;
  --md-sys-motion-spring-default-damping: 0.8;
  --md-sys-motion-spring-fast-stiffness: 700;
  --md-sys-motion-spring-effects-stiffness: 1600;
  --ease-emphasized: cubic-bezier(0.2, 0, 0, 1);
  --ease-spring: cubic-bezier(0.34, 1.36, 0.64, 1);
  --duration-short: 150ms;
  --duration-medium: 300ms;
  --duration-long: 500ms;
  --md-sys-motion-spring-default: 350ms cubic-bezier(0.34, 1.36, 0.64, 1);
  --md-sys-motion-spring-fast: 250ms cubic-bezier(0.34, 1.3, 0.64, 1);
  --md-sys-motion-spring-effects: 150ms cubic-bezier(0.2, 0, 0, 1);
}
`;

writeFileSync(new URL("../src/design/tokens.css", import.meta.url), css);

// Browser chrome colors for <meta name="theme-color">, which cannot read CSS variables.
const surfaceOf = (isDark) =>
  hexFromArgb(MaterialDynamicColors.surface.getArgb(new DynamicScheme({ sourceColorArgb: argbFromHex(SEEDS.primary), variant: TONAL_SPOT, contrastLevel: 0, isDark, ...palettes })));
writeFileSync(
  new URL("../src/design/theme-color.ts", import.meta.url),
  `// GENERATED by scripts/gen-tokens.mjs.\nexport const THEME_COLOR = { dark: "${surfaceOf(true)}", light: "${surfaceOf(false)}" } as const;\n`,
);
console.log("wrote src/design/tokens.css");

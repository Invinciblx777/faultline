// Bundles the worker and its workspace packages into dist/main.js.
// Third-party dependencies stay external and are loaded from node_modules.
import { build } from "esbuild";
import { readFileSync } from "node:fs";

const pkg = JSON.parse(readFileSync(new URL("./package.json", import.meta.url), "utf8"));
const external = Object.keys(pkg.dependencies).filter((name) => !name.startsWith("@faultline/"));
// Dependencies of workspace packages are external too.
for (const dir of ["../../packages/db", "../../packages/shared"]) {
  const dep = JSON.parse(readFileSync(new URL(`${dir}/package.json`, import.meta.url), "utf8"));
  for (const name of Object.keys(dep.dependencies ?? {})) if (!name.startsWith("@faultline/")) external.push(name);
}

await build({
  entryPoints: ["src/main.ts"],
  outfile: "dist/main.js",
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  sourcemap: true,
  external: [...new Set(external)],
  banner: { js: "// FAULTLINE worker bundle. Generated by build.mjs; do not edit." },
  logLevel: "info",
});

export interface AnalysisContext {
  db: Database;
  storage: ArtifactStorage;
  env: WorkerEnv;
  scan: Scan;
  origin: string;
  browser: Browser;
  policy: EgressPolicy;
  limits: ExecutionLimits;
  signal: AbortSignal;
  setPhase: (phase: string) => void;
  log: (message: string, extra?: Record<string, unknown>) => void;
}

interface PersistedRun {
  executionId: string;
  result: JourneyExecutionResult;
  screenshot: CapturedScreenshot | null;
  screenshotArtifactId: string | null;
}

/** Validations run per analysis; each one launches a browser through Playwright Test. */
const MAX_VALIDATIONS = 6;

function conditionsFor(journeyRef: { id: string; name: string; version: number }, journey: JourneyDefinition, config: BlastRadiusConfig, fault: ExperimentFault | null): ExecutionConditions {
  const notes: string[] = [];
  if (!fault) notes.push("No requests are altered by a fault. Mutating requests are still blocked unless the journey allows them.");
  else notes.push(describeFault(fault) + ".");
  if (fault?.kind === "unavailable") notes.push("Matching requests fail inside the browser with net::ERR_CONNECTION_REFUSED. The dependency's servers are never contacted for them.");
  if (fault?.kind === "http-error")
    notes.push(`Matching requests receive a response generated by FAULTLINE (HTTP ${fault.status}, JSON body, header x-faultline-injected). It is not a real server response.`);
  if (fault?.kind === "latency") notes.push(`Matching requests are held in the browser for ${fault.delayMs} ms and then sent unchanged; the real server time is added on top. This is per-request delay, not network throttling.`);
  if (fault?.kind === "offline")
    notes.push("Offline is emulated by the Playwright browser context after the first page loads. It is not physical network loss. Service workers are allowed so the site's own offline support can act.");
  if (fault?.kind === "narrow-viewport") notes.push("Chromium viewport emulation with touch enabled. It is not Safari and not a physical phone.");
  if (fault?.kind !== "offline") notes.push("Service workers are blocked so every request passes through FAULTLINE routing; routing also disables the HTTP cache, and each run uses a fresh browser context.");
  notes.push("Requests that could change data (POST, PUT, PATCH, DELETE) are blocked unless the journey explicitly allows the method and path.");
  return {
    network: !fault || fault.kind === "narrow-viewport" ? "normal" : fault.kind === "offline" ? "offline-emulation" : "dependency-fault",
    fault,
    steps: journey.steps.map((step, i) => `${i + 1}. ${describeStep(step)}`),
    viewport: fault?.kind === "narrow-viewport" ? "mobile" : config.viewport,
    viewportSize:
      fault?.kind === "narrow-viewport"
        ? { width: fault.width, height: fault.height, isMobile: true }
        : { width: JOURNEY_VIEWPORTS[config.viewport].width, height: JOURNEY_VIEWPORTS[config.viewport].height, isMobile: JOURNEY_VIEWPORTS[config.viewport].isMobile },
    serviceWorkers: fault?.kind === "offline" ? "allow" : "block",
    notes,
    journey: journeyRef,
  };
}

function normalize(message: string): string {
  return message.replace(/\s+/g, " ").trim().slice(0, 300);
}

/** Problems a run observed that were not injected by FAULTLINE, keyed for comparison across runs. */
function problemKeys(result: JourneyExecutionResult): Map<string, { kind: string; message: string; seq: number }> {
  const keys = new Map<string, { kind: string; message: string; seq: number }>();
  for (const event of result.events) {
    const consequence = Boolean(event.detail && (event.detail as { consequenceOfFaultInjection?: boolean }).consequenceOfFaultInjection);
    if (consequence || event.severity === "info") continue;
    if (event.kind === "console" && event.severity === "error") keys.set(`console ${normalize(event.message)}`, { kind: "console", message: event.message, seq: event.seq });
    else if (event.kind === "page_error") keys.set(`page_error ${normalize(event.message)}`, { kind: "page_error", message: event.message, seq: event.seq });
    else if (event.kind === "request_failed" || event.kind === "http_error")
      keys.set(`${event.kind} ${event.url ?? ""} ${event.statusCode ?? ""}`, { kind: event.kind, message: `${event.message}${event.url ? ` · ${event.url}` : ""}`, seq: event.seq });
  }
  return keys;
}

export async function runBlastRadiusAnalysis(ctx: AnalysisContext): Promise<{ cancelled: boolean }> {
  const { db, storage, env, scan, origin, browser, policy, limits, signal, setPhase, log } = ctx;
  const config = blastRadiusConfigSchema.parse(scan.scenarioConfig);
  if (!scan.journeySnapshot) throw new Error("The analysis has no journey snapshot to run.");
  const journey = journeyDefinitionSchema.parse(scan.journeySnapshot.definition);
  const journeyRef = { id: scan.journeySnapshot.id, name: journey.name, version: scan.journeySnapshot.version };
  const deadline = Date.now() + env.FAULTLINE_ANALYSIS_TIMEOUT_MS;
  const viewport = JOURNEY_VIEWPORTS[config.viewport];
  let experimentOrdinal = 0;

  const putArtifact = async (executionId: string, kind: ArtifactKind, name: string, shot: { buffer: Buffer; width: number; height: number; sha256?: string }, stepIndex: number | null) => {
    const key = artifactKey(scan.id, executionId, name);
    const stored = await storage.put(key, shot.buffer, "image/png");
    if (shot.sha256 && stored.sha256 !== shot.sha256) throw new Error("Artifact hash mismatch after upload");
    const [row] = await db
      .insert(artifacts)
      .values({ scanId: scan.id, executionId, kind, stepIndex, storageKey: key, contentType: "image/png", byteSize: stored.byteSize, sha256: stored.sha256, width: shot.width, height: shot.height })
      .returning({ id: artifacts.id });
    return row!.id;
  };

  const runAndPersist = async (
    role: "baseline" | "calibration" | "experiment",
    fault: ExperimentFault | null,
    experiment: { id: string; attempt: number } | null,
    label: string,
  ): Promise<PersistedRun> => {
    const ordinal = role === "experiment" ? ++experimentOrdinal : 0;
    const conditions = conditionsFor(journeyRef, journey, config, fault);
    const [execution] = await db
      .insert(scanExecutions)
      .values({
        scanId: scan.id,
        role,
        ordinal,
        experimentId: experiment?.id ?? null,
        attempt: experiment?.attempt ?? 1,
        status: "running",
        conditions,
        requestedUrl: origin,
        startedAt: new Date(),
      })
      .returning();
    if (!execution) throw new Error("Failed to create execution record");
    setPhase(label);
    const result = await runJourneyExecution({ browser, origin, journey, fault, viewport, policy, limits, signal, onPhase: (p) => setPhase(`${label} · ${p}`) });

    setPhase(`${label} · saving evidence`);
    const events = result.events.map((event) => ({
      executionId: execution.id,
      seq: event.seq,
      kind: event.kind,
      severity: event.severity,
      occurredAt: new Date(event.occurredAt),
      offsetMs: event.offsetMs,
      message: event.message,
      url: event.url ?? null,
      resourceType: event.resourceType ?? null,
      method: event.method ?? null,
      statusCode: event.statusCode ?? null,
      detail: event.detail ?? null,
    }));
    for (let i = 0; i < events.length; i += 250) await db.insert(executionEvents).values(events.slice(i, i + 250));
    const requests = result.requests.map((r) => ({ executionId: execution.id, ...r }));
    for (let i = 0; i < requests.length; i += 250) await db.insert(networkRequests).values(requests.slice(i, i + 250));

    const stepArtifacts = new Map<number, string>();
    for (const { stepIndex, shot } of result.stepScreenshots) {
      stepArtifacts.set(stepIndex, await putArtifact(execution.id, "step-screenshot", `step-${stepIndex}`, shot, stepIndex));
    }
    const rows = [...result.steps, ...result.offlineChecks].map((s) => ({
      executionId: execution.id,
      phase: s.phase,
      stepIndex: s.index,
      stepType: s.type,
      description: s.description,
      isAssertion: s.isAssertion,
      status: s.status,
      startedAt: s.startedAt,
      finishedAt: s.finishedAt,
      offsetMs: s.offsetMs,
      durationMs: s.durationMs,
      error: s.error,
      detail: { ...(s.detail ?? {}), ...(s.phase === "journey" && stepArtifacts.has(s.index) ? { screenshotArtifactId: stepArtifacts.get(s.index) } : {}) },
    }));
    if (rows.length) await db.insert(stepResults).values(rows);

    const screenshotArtifactId = result.screenshot ? await putArtifact(execution.id, "screenshot", "screenshot", result.screenshot, null) : null;
    const cancelled = result.interrupted === "cancelled";
    await db
      .update(scanExecutions)
      .set({
        status: result.engineError ? "failed" : "completed",
        outcome: result.outcome,
        failureMessage: cancelled ? "Cancelled by operator during execution." : result.engineError,
        finalUrl: result.finalUrl,
        httpStatus: result.httpStatus,
        pageTitle: result.pageTitle,
        navigationError: result.navigationError,
        browserName: result.browserName,
        browserVersion: result.browserVersion,
        userAgent: result.userAgent,
        viewport: result.viewport,
        summary: result.summary,
        startedAt: result.startedAt,
        finishedAt: result.finishedAt,
        durationMs: result.durationMs,
      })
      .where(eq(scanExecutions.id, execution.id));
    log("journey execution finished", {
      scanId: scan.id,
      role,
      ordinal,
      steps: result.steps.map((s) => s.status[0]).join(""),
      faultApplications: result.observation.faultApplications,
      engineError: result.engineError,
    });
    return { executionId: execution.id, result, screenshot: result.screenshot, screenshotArtifactId };
  };

  // 1. Baseline and an independent calibration run under normal conditions.
  const baseline = await runAndPersist("baseline", null, null, "Baseline journey (normal conditions)");
  if (signal.aborted) return { cancelled: true };
  const calibration = await runAndPersist("calibration", null, null, "Calibration journey (normal conditions)");
  if (signal.aborted) return { cancelled: true };

  // 2. Dependencies from traffic the browser really produced in both normal runs.
  setPhase("Discovering dependencies from observed traffic");
  const observed: ObservedRequest[] = [...baseline.result.requests, ...calibration.result.requests].map((r) => ({
    url: r.url,
    method: r.method,
    resourceType: r.resourceType,
    status: r.status,
    durationMs: r.durationMs,
    outcome: r.outcome,
    isMainDocument: r.isMainDocument,
  }));
  const discovered = discoverDependencies(observed, origin);
  const dependencyIds = new Map<string, string>();
  for (const group of discovered) {
    const steps = [...new Set(baseline.result.requests.filter((r) => r.dependencyKey === group.key && r.stepIndex !== null).map((r) => r.stepIndex!))].sort((a, b) => a - b);
    const [row] = await db
      .insert(dependencies)
      .values({
        scanId: scan.id,
        key: group.key,
        label: group.label,
        scope: group.scope,
        party: group.party,
        origin: group.origin,
        method: group.method,
        pathPattern: group.pathPattern,
        resourceTypes: group.resourceTypes,
        matcher: group.matcher,
        requestCount: group.requestCount,
        failedCount: group.failedCount,
        statuses: group.statuses,
        medianDurationMs: group.medianDurationMs,
        sampleUrls: group.sampleUrls,
        eligibleFaults: group.eligibleFaults,
        ineligibleReason: group.ineligibleReason,
        requestedDuringSteps: steps,
      })
      .returning({ id: dependencies.id });
    dependencyIds.set(group.key, row!.id);
  }

  // 3. Baseline stability and visual variability.
  const stableSteps = journey.steps.flatMap((_, i) =>
    baseline.result.observation.steps[i]?.status === "passed" && calibration.result.observation.steps[i]?.status === "passed" ? [i] : [],
  );
  const excludedSteps = journey.steps.flatMap((_, i) => {
    const b = baseline.result.observation.steps[i]?.status;
    const c = calibration.result.observation.steps[i]?.status;
    if (b === "passed" && c === "passed") return [];
    return [{ index: i, reason: b === c ? `Did not pass in either normal run (${b}).` : `Unstable: ${b} in the baseline, ${c} in the calibration run.` }];
  });
  let calibrationRatio: number | null = null;
  let calibrationNote = "No calibration comparison: one of the normal runs has no screenshot.";
  let comparedPixels: number | null = null;
  if (baseline.screenshot && calibration.screenshot) {
    const comparison = compareScreenshots(baseline.screenshot.buffer, calibration.screenshot.buffer);
    calibrationRatio = comparison.diffRatio;
    comparedPixels = comparison.unionPixels;
    calibrationNote = `Baseline and calibration screenshots differ by ${comparison.diffPixels} of ${comparison.unionPixels} pixels (${(comparison.diffRatio * 100).toFixed(2)}%).`;
    await putArtifact(calibration.executionId, "diff", "diff", { buffer: comparison.diffPng, width: comparison.overlap.width, height: comparison.overlap.height }, null);
  }
  const threshold = visualThreshold(calibrationRatio);

  // 4. Plan isolated experiments. Every candidate not scheduled is recorded with its reason.
  const plan = planExperiments(discovered, config);
  const experimentRows = [];
  for (const planned of plan.planned) {
    const group = planned.dependencyKey ? discovered.find((d) => d.key === planned.dependencyKey) : null;
    const [row] = await db
      .insert(experiments)
      .values({
        scanId: scan.id,
        ordinal: planned.ordinal,
        kind: planned.kind,
        dependencyId: planned.dependencyKey ? (dependencyIds.get(planned.dependencyKey) ?? null) : null,
        dependencyKey: planned.dependencyKey,
        dependencyLabel: group?.label ?? null,
        fault: planned.fault,
      })
      .returning();
    experimentRows.push(row!);
  }
  const summary: AnalysisSummary = {
    baselineExecutionId: baseline.executionId,
    calibrationExecutionId: calibration.executionId,
    excludedSteps,
    stableSteps,
    calibration: { screenshotDiffRatio: calibrationRatio, comparedPixels, note: calibrationNote },
    visualThreshold: threshold,
    skippedCandidates: plan.skipped,
    dependencyCount: discovered.length,
    plannedExperiments: plan.planned.length,
  };
  await db.update(scans).set({ analysis: summary }).where(eq(scans.id, scan.id));

  const baselineProblems = new Map([...problemKeys(baseline.result), ...problemKeys(calibration.result)]);
  const baselineFailedDeps = new Set(
    [...baseline.result.requests, ...calibration.result.requests].filter((r) => r.outcome === "failed" || (r.status ?? 0) >= 400).map((r) => r.dependencyKey),
  );

  // 5. Experiments, one condition at a time, each in a fresh browser context.
  const findings: Array<{ experimentId: string; evaluation: ExperimentEvaluation & { reproducibility: Reproducibility }; fault: ExperimentFault; label: string | null; viewport: { width: number; height: number; isMobile: boolean } }> = [];
  for (const [index, experiment] of experimentRows.entries()) {
    if (signal.aborted) return { cancelled: true };
    if (Date.now() > deadline) {
      await db
        .update(experiments)
        .set({ status: "skipped", failureMessage: `The analysis time budget of ${env.FAULTLINE_ANALYSIS_TIMEOUT_MS} ms was reached before this experiment started.` })
        .where(and(eq(experiments.id, experiment.id), eq(experiments.status, "pending")));
      continue;
    }
    const label = `Experiment ${index + 1} of ${experimentRows.length}: ${experiment.dependencyLabel ?? experiment.kind}`;
    const startedAt = new Date();
    await db.update(experiments).set({ status: "running", startedAt }).where(eq(experiments.id, experiment.id));
    try {
      const first = await runAndPersist("experiment", experiment.fault, { id: experiment.id, attempt: 1 }, label);
      if (first.result.interrupted === "cancelled") return { cancelled: true };
      const evaluate = (run: PersistedRun) =>
        evaluateExperiment({ journey, kind: experiment.kind, baseline: baseline.result.observation, calibration: calibration.result.observation, experiment: run.result.observation });
      const firstEvaluation = evaluate(first);
      let second: ExperimentEvaluation | null = null;
      if (config.confirmFindings && isFinding(firstEvaluation.verdict) && !signal.aborted) {
        const repeat = await runAndPersist("experiment", experiment.fault, { id: experiment.id, attempt: 2 }, `${label} · confirmation run`);
        if (repeat.result.interrupted === "cancelled") return { cancelled: true };
        second = evaluate(repeat);
      }
      const evaluation = combineAttempts(firstEvaluation, second);

      const newErrors: ExperimentNewError[] = [];
      for (const [key, problem] of problemKeys(first.result)) {
        if (!baselineProblems.has(key) && newErrors.length < 25) newErrors.push({ kind: problem.kind, message: redactText(problem.message, 500), executionId: first.executionId, seq: problem.seq });
      }
      const newFailedRequestCount = first.result.requests.filter(
        (r) => !r.injected && (r.outcome === "failed" || (r.status ?? 0) >= 400) && !baselineFailedDeps.has(r.dependencyKey),
      ).length;

      let visual: { diffRatio: number | null; threshold: number | null; significant: boolean | null; note: string; diffArtifactId: string | null } = {
        diffRatio: null,
        threshold: threshold.ratio,
        significant: null,
        note: "Not compared: the baseline or the experiment has no final screenshot.",
        diffArtifactId: null,
      };
      if (baseline.screenshot && first.screenshot) {
        const comparison = compareScreenshots(baseline.screenshot.buffer, first.screenshot.buffer);
        const diffArtifactId = await putArtifact(first.executionId, "diff", "diff", { buffer: comparison.diffPng, width: comparison.overlap.width, height: comparison.overlap.height }, null);
        const significant = comparison.diffRatio > threshold.ratio;
        const sizeNote =
          comparison.sizes.a.height !== comparison.sizes.b.height || comparison.sizes.a.width !== comparison.sizes.b.width
            ? ` Page size changed from ${comparison.sizes.a.width}×${comparison.sizes.a.height} to ${comparison.sizes.b.width}×${comparison.sizes.b.height}; pixels outside the overlap count as changed.`
            : "";
        visual = {
          diffRatio: comparison.diffRatio,
          threshold: threshold.ratio,
          significant,
          note: `${(comparison.diffRatio * 100).toFixed(2)}% of pixels changed versus the baseline; ${significant ? "above" : "within"} the ${(threshold.ratio * 100).toFixed(2)}% threshold.${sizeNote} A visual difference is an observed association with the fault, not proof that the fault caused it.`,
          diffArtifactId,
        };
      }

      const finishedAt = new Date();
      await db
        .update(experiments)
        .set({
          status: evaluation.verdict === "test_failed" ? "failed" : "completed",
          verdict: evaluation.verdict,
          reproducibility: evaluation.reproducibility,
          reasons: evaluation.reasons,
          affectedSteps: evaluation.affectedSteps,
          usableAssertions: evaluation.usableAssertions,
          excludedSteps: evaluation.excludedSteps,
          newErrors,
          affectedRequestCount: first.result.observation.faultApplications,
          newFailedRequestCount,
          visual,
          failureMessage: first.result.engineError,
          finishedAt,
          durationMs: finishedAt.getTime() - startedAt.getTime(),
        })
        .where(eq(experiments.id, experiment.id));
      log("experiment finished", { scanId: scan.id, experiment: experiment.ordinal, verdict: evaluation.verdict, reproducibility: evaluation.reproducibility });
      if (isFinding(evaluation.verdict)) {
        findings.push({ experimentId: experiment.id, evaluation, fault: experiment.fault, label: experiment.dependencyLabel, viewport: first.result.viewport });
      }
    } catch (error) {
      if (signal.aborted) return { cancelled: true };
      const message = error instanceof Error ? error.message.split("\n")[0]! : String(error);
      log("experiment failed", { scanId: scan.id, experiment: experiment.ordinal, error: message });
      await db
        .update(experiments)
        .set({
          status: "failed",
          verdict: "test_failed",
          reproducibility: "not-applicable",
          reasons: [{ code: "engine_error", message: `FAULTLINE could not run this experiment: ${redactText(message, 400)}` }],
          failureMessage: redactText(message, 1000),
          finishedAt: new Date(),
        })
        .where(eq(experiments.id, experiment.id));
    }
  }

  // 6. Executable regression tests for findings, validated with the real Playwright Test runner.
  let validations = 0;
  for (const finding of findings) {
    if (signal.aborted) return { cancelled: true };
    const generated = generateRegressionTest({
      journey,
      journeyRef: { id: journeyRef.id, version: journeyRef.version },
      analyzedOrigin: origin,
      viewport: finding.viewport,
      stableSteps,
      includeBudgets: finding.evaluation.verdict === "degraded",
      experiment: {
        id: finding.experimentId,
        scanId: scan.id,
        verdict: finding.evaluation.verdict,
        fault: finding.fault,
        dependencyLabel: finding.label,
        observedAt: new Date().toISOString(),
        reasons: finding.evaluation.reasons.map((r) => r.message),
      },
    });
    const [row] = await db
      .insert(regressionTests)
      .values({
        experimentId: finding.experimentId,
        scanId: scan.id,
        filename: generated.filename,
        content: generated.content,
        sha256: createHash("sha256").update(generated.content).digest("hex"),
        command: generated.command,
      })
      .returning({ id: regressionTests.id });
    if (!env.FAULTLINE_REGRESSION_VALIDATION || validations >= MAX_VALIDATIONS || Date.now() > deadline) continue;
    validations += 1;
    setPhase(`Validating regression test ${validations} with Playwright Test (${VERDICT_LABELS[finding.evaluation.verdict]}: ${finding.label ?? finding.fault.kind})`);
    try {
      const validation = await validateRegressionTest({
        filename: generated.filename,
        content: generated.content,
        targetOrigin: origin,
        policy,
        maxTransferBytes: limits.maxTransferBytes,
        chromiumSandbox: env.FAULTLINE_CHROMIUM_SANDBOX,
        timeoutMs: 180_000,
      });
      await db
        .update(regressionTests)
        .set({ validationStatus: validation.status, validationSummary: validation.summary, validationOutput: validation.output, validatedAt: new Date() })
        .where(eq(regressionTests.id, row!.id));
      log("regression test validated", { scanId: scan.id, experimentId: finding.experimentId, status: validation.status, ms: validation.durationMs });
    } catch (error) {
      const message = error instanceof Error ? error.message : String(error);
      await db
        .update(regressionTests)
        .set({ validationStatus: "error", validationSummary: `Validation could not run: ${redactText(message, 400)}`, validatedAt: new Date() })
        .where(eq(regressionTests.id, row!.id));
    }
  }
  return { cancelled: signal.aborted };
}

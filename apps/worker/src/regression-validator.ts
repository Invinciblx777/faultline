import { spawn } from "node:child_process";
import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { redactText } from "@faultline/shared";
import type { EgressPolicy } from "@faultline/shared/network";
import { EgressGuard } from "./egress-guard";

/**
 * Executes a generated regression test with the real Playwright Test runner,
 * exactly as a developer would, and reports what happened.
 *
 * The browser is still forced through FAULTLINE's egress guard (via the
 * config file written next to the test, using credentials passed through the
 * environment), so validation obeys the same allowlist and private-network
 * policy as every other execution.
 */

export type ValidationStatus = "fails_as_expected" | "passes" | "error";

export interface ValidationResult {
  status: ValidationStatus;
  summary: string;
  output: string;
  durationMs: number;
}

const WORKER_ROOT = fileURLToPath(new URL("..", import.meta.url));
/** Under the worker package so `@playwright/test` resolves from its node_modules. Git-ignored. */
export const VALIDATION_ROOT = join(WORKER_ROOT, ".regression-runs");

const CONFIG = `// Generated by FAULTLINE for validation only. Not part of the exported test.
const sandbox = process.env.FAULTLINE_VALIDATION_SANDBOX === "true";
export default {
  testDir: ".",
  testMatch: /\\.spec\\.ts$/,
  workers: 1,
  retries: 0,
  forbidOnly: true,
  outputDir: "./results",
  reporter: [["json", { outputFile: "report.json" }]],
  use: {
    browserName: "chromium",
    headless: true,
    trace: "off",
    screenshot: "off",
    video: "off",
    proxy: {
      server: process.env.FAULTLINE_VALIDATION_PROXY_SERVER,
      username: process.env.FAULTLINE_VALIDATION_PROXY_USERNAME,
      password: process.env.FAULTLINE_VALIDATION_PROXY_PASSWORD,
    },
    launchOptions: {
      chromiumSandbox: sandbox,
      args: ["--force-webrtc-ip-handling-policy=disable_non_proxied_udp", "--webrtc-ip-handling-policy=disable_non_proxied_udp", "--disable-dev-shm-usage"],
    },
  },
};
`;

interface JsonReport {
  stats?: { expected?: number; unexpected?: number; flaky?: number; skipped?: number };
  errors?: Array<{ message?: string }>;
  suites?: JsonSuite[];
}
interface JsonSuite {
  suites?: JsonSuite[];
  specs?: Array<{ title: string; tests?: Array<{ results?: Array<{ status?: string; error?: { message?: string } }> }> }>;
}

function firstError(report: JsonReport): string | null {
  const stack: JsonSuite[] = [...(report.suites ?? [])];
  while (stack.length) {
    const suite = stack.shift()!;
    for (const spec of suite.specs ?? []) {
      for (const test of spec.tests ?? []) {
        for (const result of test.results ?? []) {
          if (result.error?.message) return result.error.message;
        }
      }
    }
    stack.push(...(suite.suites ?? []));
  }
  return report.errors?.[0]?.message ?? null;
}

const ANSI = /\u001b\[[0-9;]*m/g;

export async function validateRegressionTest(input: {
  filename: string;
  content: string;
  targetOrigin: string;
  policy: EgressPolicy;
  maxTransferBytes: number;
  chromiumSandbox: boolean;
  timeoutMs: number;
}): Promise<ValidationResult> {
  const started = Date.now();
  if (!/^[a-z0-9-]+\.spec\.ts$/.test(input.filename)) throw new Error("Refusing to write an unexpected regression test filename");
  const dir = join(VALIDATION_ROOT, randomUUID());
  const guard = new EgressGuard({ policy: input.policy, maxTransferBytes: input.maxTransferBytes });
  await mkdir(dir, { recursive: true });
  try {
    await writeFile(join(dir, input.filename), input.content, "utf8");
    await writeFile(join(dir, "playwright.config.mjs"), CONFIG, "utf8");
    const proxy = await guard.start();
    const cli = createRequire(join(WORKER_ROOT, "package.json")).resolve("@playwright/test/cli");
    const { code, output, timedOut } = await new Promise<{ code: number | null; output: string; timedOut: boolean }>((resolve) => {
      const child = spawn(process.execPath, [cli, "test", "--config", "playwright.config.mjs"], {
        cwd: dir,
        env: {
          PATH: process.env.PATH ?? "",
          HOME: process.env.HOME ?? "",
          ...(process.env.PLAYWRIGHT_BROWSERS_PATH ? { PLAYWRIGHT_BROWSERS_PATH: process.env.PLAYWRIGHT_BROWSERS_PATH } : {}),
          FAULTLINE_TARGET_URL: input.targetOrigin,
          FAULTLINE_VALIDATION_PROXY_SERVER: proxy.server,
          FAULTLINE_VALIDATION_PROXY_USERNAME: proxy.username,
          FAULTLINE_VALIDATION_PROXY_PASSWORD: proxy.password,
          FAULTLINE_VALIDATION_SANDBOX: String(input.chromiumSandbox),
          CI: "1",
          FORCE_COLOR: "0",
        },
        stdio: ["ignore", "pipe", "pipe"],
      });
      let buffer = "";
      const collect = (chunk: Buffer) => {
        if (buffer.length < 64_000) buffer += chunk.toString();
      };
      child.stdout.on("data", collect);
      child.stderr.on("data", collect);
      let timedOut = false;
      const timer = setTimeout(() => {
        timedOut = true;
        child.kill("SIGKILL");
      }, input.timeoutMs);
      child.on("close", (exitCode) => {
        clearTimeout(timer);
        resolve({ code: exitCode, output: buffer, timedOut });
      });
    });
    const report = await readFile(join(dir, "report.json"), "utf8")
      .then((text) => JSON.parse(text) as JsonReport)
      .catch(() => null);
    const cleanOutput = redactText(output.replace(ANSI, ""), 8_000);
    const durationMs = Date.now() - started;
    if (timedOut) return { status: "error", summary: `The test runner did not finish within ${input.timeoutMs} ms.`, output: cleanOutput, durationMs };
    const expected = report?.stats?.expected ?? 0;
    const unexpected = report?.stats?.unexpected ?? 0;
    const error = report ? firstError(report) : null;
    const errorLine = error ? redactText(error.replace(ANSI, "").split("\n").filter(Boolean).slice(0, 4).join(" · "), 600) : null;
    if (code === 0 && expected > 0 && unexpected === 0) {
      return { status: "passes", summary: `Passed against ${input.targetOrigin}: the application tolerated the fault in this run.`, output: cleanOutput, durationMs };
    }
    if (unexpected > 0) {
      return {
        status: "fails_as_expected",
        summary: `Failed against ${input.targetOrigin}, reproducing the finding${errorLine ? `: ${errorLine}` : "."}`,
        output: cleanOutput,
        durationMs,
      };
    }
    return {
      status: "error",
      summary: `The test runner exited with code ${code} without a test result${errorLine ? `: ${errorLine}` : "."}`,
      output: cleanOutput,
      durationMs,
    };
  } finally {
    await guard.stop();
    await rm(dir, { recursive: true, force: true }).catch(() => undefined);
  }
}
